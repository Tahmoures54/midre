export const messages = { fa, en };

export type MessageKey = keyof typeof fa;

function interpolate(template: string, vars?: Vars): string {
  if (!vars) return template;
  let out = template;
  for (const [key, value] of Object.entries(vars)) {
    out = out.replaceAll(`{${key}}`, String(value));
  }
  return out;
}

function readStoredLocale(): Locale {
  if (typeof window === "undefined") return "fa";
  try {
    const query = new URLSearchParams(window.location.search).get("lang");
    if (query === "en" || query === "fa") return query;
    const saved = window.localStorage.getItem(KEY);
    if (saved === "en" || saved === "fa") return saved;
  } catch {
    /* ignore */
  }
  return "fa";
}

function persistLocale(locale: Locale) {
  if (typeof window === "undefined") return;
  window.localStorage.setItem(KEY, locale);
  document.documentElement.lang = locale === "fa" ? "fa" : "en";
  document.documentElement.dir = locale === "fa" ? "rtl" : "ltr";
  document.title = messages[locale].appName;
}

interface LocaleStore {
  locale: Locale;
  setLocale: (locale: Locale) => void;
}

export const useLocaleStore = create<LocaleStore>((set) => ({
  locale: "fa",
  setLocale: (locale) => {
    persistLocale(locale);
    set({ locale });
  },
}));

export function bootLocale(): Locale {
  const locale = readStoredLocale();
  persistLocale(locale);
  useLocaleStore.setState({ locale });
  return locale;
}

export function getLocale(): Locale {
  return useLocaleStore.getState().locale;
}

export function t(key: MessageKey, vars?: Vars, locale: Locale = getLocale()): string {
  return interpolate(messages[locale][key], vars);
}

export function dateLocale(locale: Locale = getLocale()): string {
  return locale === "fa" ? "fa-IR" : "en-US";
}

export function nagMessageKey(seconds: number): MessageKey {
  const key = `nag${seconds}` as MessageKey;
  return key in messages.fa ? key : "nag45";
}

export function statusMessageKey(status: "on-time" | "early" | "late" | "missed" | "snoozed" | "skipped"): MessageKey {
  if (status === "on-time") return "onTime";
  return status;
}

export function useI18n() {
  const locale = useLocaleStore((s) => s.locale);
  const setLocale = useLocaleStore((s) => s.setLocale);
  return {
    locale,
    setLocale,
    dir: locale === "fa" ? ("rtl" as const) : ("ltr" as const),
    t: (key: MessageKey, vars?: Vars) => t(key, vars, locale),
  };
}
